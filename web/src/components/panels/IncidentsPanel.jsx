import { api } from '../../api/client.js'
import { STANDALONE } from '../../config.js'
import { incidentBounds, incidentNumber, incidentPlace, replayIncident } from '../../lib/incidents.js'
import { duration, istTime } from '../../lib/time.js'
import { useDerived, useStore, useViewTick } from '../../store.js'
import { InjectedBadge, SectionTitle } from '../ui.jsx'

export function ReportLink({ id, className = '' }) {
  if (STANDALONE) {
    return (
      <span className={`inline-flex items-center rounded-md border border-dashed border-sand-400 px-2.5 py-1 text-[13px] text-ink-600 ${className}`} title="The PDF is generated by the backend">
        PDF needs the backend
      </span>
    )
  }
  return (
    <a
      href={api.reportUrl(id)}
      onClick={(e) => e.stopPropagation()}
      className={`inline-flex items-center gap-1 rounded-md border border-sand-400 bg-sand-50 px-2.5 py-1 text-[13px] font-semibold text-ink-700 hover:bg-air-50 ${className}`}
      download={`incident-${id}.pdf`}
    >
      <svg width="13" height="13" viewBox="0 0 16 16" aria-hidden="true">
        <path d="M8 1.5v8.5M4.5 6.8 8 10.3l3.5-3.5M2.5 13.5h11" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" />
      </svg>
      Report (PDF)
    </a>
  )
}

const KIND = {
  jamming: { word: 'GPS jamming', tone: '#E5484D', ink: '#8F1F23', soft: '#FCECEC' },
  spoofing: { word: 'Suspected spoofing', tone: '#9B5DE5', ink: '#5B2E9A', soft: '#F3ECFC' },
}

export function IncidentCard({ inc }) {
  const d = useDerived()
  const focus = useStore((s) => s.replayFocus)
  const k = KIND[inc.kind] || KIND.jamming
  const num = incidentNumber(inc)
  const place = incidentPlace(inc)
  const active = focus?.id === inc.id
  const lasted = inc.closed_ts ? duration(inc.closed_ts - inc.opened_ts) : null
  const replay = () => replayIncident(inc, d.cellsById)

  return (
    <article
      role="button"
      tabIndex={0}
      onClick={replay}
      onKeyDown={(e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault()
          replay()
        }
      }}
      aria-label={`Incident ${num}, ${k.word}. Click to replay it from just before it started.`}
      className={`group cursor-pointer rounded-lg border bg-sand-50 transition hover:shadow-float focus:outline-none focus-visible:ring-2 focus-visible:ring-air-600 ${
        active ? 'ring-2 ring-air-600' : ''
      }`}
      style={{ borderColor: inc.open ? k.tone : '#D8CCAE', borderLeftWidth: 5 }}
    >
      <div className="px-3 pb-2.5 pt-2">
        <div className="flex items-start gap-2">
          <div className="min-w-0 flex-1">
            <p className="text-[12px] font-semibold uppercase tracking-wide" style={{ color: k.ink }}>
              {k.word} · #{num}
            </p>
            <h3 className="truncate text-[16px] font-bold leading-snug text-ink-900" title={place?.text}>
              {place ? place.text.replace(/^./, (x) => x.toUpperCase()) : 'Location unknown'}
            </h3>
          </div>
          <span
            className={`mt-0.5 shrink-0 rounded px-1.5 text-[12px] font-bold leading-[1.7] ${inc.open ? 'text-white' : 'bg-sand-200 text-ink-700'}`}
            style={inc.open ? { background: k.tone } : undefined}
          >
            {inc.open ? 'Ongoing' : 'Ended'}
          </span>
        </div>

        <dl className="mt-1.5 grid grid-cols-3 gap-2 text-[13px]">
          <div>
            <dt className="text-[11.5px] text-ink-600">Started</dt>
            <dd className="font-data font-semibold text-ink-900 tnum">{istTime(inc.opened_ts)}</dd>
          </div>
          <div>
            <dt className="text-[11.5px] text-ink-600">{inc.open ? 'Status' : 'Lasted'}</dt>
            <dd className="font-semibold text-ink-900">{inc.open ? 'still on' : lasted}</dd>
          </div>
          <div>
            <dt className="text-[11.5px] text-ink-600">Aircraft hit</dt>
            <dd className="font-semibold text-ink-900">
              {inc.n_aircraft}
              {inc.kind === 'jamming' && inc.max_frac_bad ? <span className="font-normal text-ink-600"> ({Math.round(inc.max_frac_bad * 100)}% peak)</span> : null}
            </dd>
          </div>
        </dl>

        {inc.injected ? (
          <div className="mt-2">
            <InjectedBadge />
          </div>
        ) : null}

        <div className="mt-2.5 flex flex-wrap items-center gap-2">
          <span className="inline-flex items-center gap-1.5 rounded-md bg-air-600 px-2.5 py-1 text-[13px] font-semibold text-white group-hover:bg-air-700">
            <svg width="11" height="11" viewBox="0 0 14 14" aria-hidden="true">
              <path d="M3 1.5v11l9-5.5z" fill="currentColor" />
            </svg>
            {active ? 'Replaying' : 'Replay it'}
          </span>
          <ReportLink id={inc.id} />
        </div>
      </div>
    </article>
  )
}

export default function IncidentsPanel() {
  const d = useDerived()
  const tick = useViewTick()
  const incidents = [...d.incidents].sort((a, b) => Number(b.open) - Number(a.open) || b.opened_ts - a.opened_ts)
  const nOpen = incidents.filter((i) => i.open).length
  return (
    <section aria-labelledby="incidents-title" className="space-y-2.5">
      <SectionTitle aside={tick ? `${nOpen} ongoing · ${incidents.length - nOpen} ended` : null}>
        <span id="incidents-title">Incidents</span>
      </SectionTitle>
      {incidents.length ? (
        <>
          <p className="text-[12.5px] leading-snug text-ink-600">Click an incident to replay the recording from 1.5 min before it started.</p>
          <div className="space-y-2">
            {incidents.map((inc) => (
              <IncidentCard key={inc.id} inc={inc} />
            ))}
          </div>
        </>
      ) : (
        <p className="rounded-lg border border-dashed border-sand-400 p-3 text-[14px] leading-snug text-ink-600">
          No incidents yet. One opens, with a PDF report, as soon as a hexagon turns jammed or spoofing.
        </p>
      )}
    </section>
  )
}

