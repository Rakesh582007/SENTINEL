import { api } from '../../api/client.js'
import { STANDALONE } from '../../config.js'
import { fmtLatLon } from '../../lib/geo.js'
import { istTime } from '../../lib/time.js'
import { useDerived, useStore } from '../../store.js'
import { InjectedBadge, SectionTitle } from '../ui.jsx'

function incidentBounds(inc, d) {
  const pts = []
  for (const h of inc.cells || []) {
    const c = d.cellsById.get(h)
    if (c) for (const [lon, lat] of c.ring) pts.push([lat, lon])
  }
  if (inc.est_lat != null && inc.est_radius_km) {
    const dLat = inc.est_radius_km / 111.2
    const dLon = dLat / Math.cos((inc.est_lat * Math.PI) / 180)
    pts.push([inc.est_lat - dLat, inc.est_lon - dLon], [inc.est_lat + dLat, inc.est_lon + dLon])
  }
  if (!pts.length) return null
  const lats = pts.map((p) => p[0])
  const lons = pts.map((p) => p[1])
  return [
    [Math.min(...lats), Math.min(...lons)],
    [Math.max(...lats), Math.max(...lons)],
  ]
}

export function ReportLink({ id, className = '' }) {
  if (STANDALONE) {
    return (
      <span className={`inline-flex items-center rounded-md border border-dashed border-sand-400 px-2.5 py-1 text-[13px] text-ink-600 ${className}`} title="The PDF is generated by the backend">
        PDF report needs the backend
      </span>
    )
  }
  return (
    <a
      href={api.reportUrl(id)}
      className={`inline-flex items-center rounded-md bg-air-600 px-2.5 py-1 text-[13px] font-semibold text-white hover:bg-air-700 ${className}`}
      download={`incident-${id}.pdf`}
    >
      Download report (PDF)
    </a>
  )
}

export function IncidentCard({ inc }) {
  const d = useDerived()
  const focusOn = useStore((s) => s.focusOn)
  const kind = inc.kind === 'jamming' ? 'Jamming' : 'Suspected spoofing'
  const tone = inc.kind === 'jamming' ? '#E5484D' : '#9B5DE5'
  const bounds = incidentBounds(inc, d)
  return (
    <article className="rounded-lg border bg-sand-50 p-3" style={{ borderColor: inc.open ? tone : '#C8B78F', borderWidth: 1.5 }}>
      <div className="flex flex-wrap items-center gap-1.5">
        <h3 className="text-[15.5px] font-bold text-ink-900">{kind}</h3>
        <span className="font-data text-[12px] text-ink-600">{inc.id}</span>
        <span
          className={`rounded px-1.5 text-[12px] font-bold leading-[1.6] ${inc.open ? 'text-white' : 'bg-sand-200 text-ink-700'}`}
          style={inc.open ? { background: tone } : undefined}
        >
          {inc.open ? 'Open' : 'Closed'}
        </span>
        {inc.injected ? <InjectedBadge /> : null}
      </div>
      <p className="mt-1 text-[13.5px] text-ink-700">
        Opened <span className="font-data tnum">{istTime(inc.opened_ts)}</span> IST
        {inc.closed_ts ? (
          <>
            , closed <span className="font-data tnum">{istTime(inc.closed_ts)}</span>
          </>
        ) : null}
        . {inc.n_aircraft} aircraft affected
        {inc.max_frac_bad ? `, peak ${Math.round(inc.max_frac_bad * 100)}% with bad GPS` : ''}.
      </p>
      {inc.kind === 'jamming' && inc.est_lat != null ? (
        <p className="mt-1 text-[13px] leading-snug text-ink-600">
          Approximate area for investigation: <span className="font-data text-ink-900">{fmtLatLon(inc.est_lat, inc.est_lon)}</span>, about{' '}
          {Math.round(inc.est_radius_km)} km radius.
        </p>
      ) : null}
      <div className="mt-2 flex flex-wrap gap-2">
        <ReportLink id={inc.id} />
        {bounds ? (
          <button
            type="button"
            className="rounded-md border border-sand-400 px-2.5 py-1 text-[13px] font-semibold text-ink-700 hover:bg-air-50"
            onClick={() => focusOn({ bounds, maxZoom: 8 })}
          >
            Show on map
          </button>
        ) : null}
      </div>
    </article>
  )
}

export default function IncidentsPanel() {
  const d = useDerived()
  const tick = useStore((s) => s.tick)
  const incidents = [...d.incidents].sort((a, b) => Number(b.open) - Number(a.open) || b.opened_ts - a.opened_ts)
  return (
    <section aria-labelledby="incidents-title" className="space-y-2.5">
      <SectionTitle aside={tick ? `${incidents.filter((i) => i.open).length} open` : null}>
        <span id="incidents-title">Incidents</span>
      </SectionTitle>
      {incidents.length ? (
        <div className="space-y-2">
          {incidents.map((inc) => (
            <IncidentCard key={inc.id} inc={inc} />
          ))}
        </div>
      ) : (
        <p className="rounded-lg border border-dashed border-sand-400 p-3 text-[14px] leading-snug text-ink-600">
          No incidents yet. One opens, with a PDF report, as soon as a hexagon turns jammed or spoofing.
        </p>
      )}
      {tick?.mode === 'replay' ? (
        <p className="text-[12.5px] leading-snug text-ink-600">Replay loops: each loop clears incidents and they open again as the data repeats.</p>
      ) : null}
    </section>
  )
}
